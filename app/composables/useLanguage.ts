export function useLanguage() {
  const locale = useCookie<Language>('ppi-language', {
    default: () => 'fr',
    maxAge: 60 * 60 * 24 * 365,
    sameSite: 'lax',
  })

  const language = computed<Language>(() => locale.value === 'en' ? 'en' : 'fr')
  const copy = computed(() => messages[language.value])

  const setLanguage = (value: Language) => {
    locale.value = value
  }

  return { language, copy, setLanguage }
}
